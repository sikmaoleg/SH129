/** Подставляет реквизиты оператора в текст документа. */
function legalRender(string $html): string
{
    return strtr($html, [
        '{OPERATOR}'            => legalOperatorHtml(),
        'href="privacy.php"'    => 'href="' . url('privacy.php') . '"',
        'href="consent.php"'    => 'href="' . url('consent.php') . '"',
        'href="consent-public.php"' => 'href="' . url('consent-public.php') . '"',
    ]);
}

