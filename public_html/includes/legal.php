/** Блок с реквизитами оператора. */
function legalOperatorHtml(): string
{
    $o = operatorInfo();
    $rows = ['<b>' . e($o['name']) . '</b>'];
    if ($o['inn'] !== '')     $rows[] = 'ИНН ' . e($o['inn']);
    if ($o['ogrn'] !== '')    $rows[] = 'ОГРН ' . e($o['ogrn']);
    if ($o['address'] !== '') $rows[] = 'Адрес: ' . e($o['address']);
    if ($o['email'] !== '')   $rows[] = 'Электронная почта: <a href="mailto:' . e($o['email']) . '">' . e($o['email']) . '</a>';
    return '<p class="legal-op">' . implode('<br>', $rows) . '</p>';
}

function legalDate(): string
{
    return ruDate(CONSENT_VERSION);
}

